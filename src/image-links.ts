import { requestUrl } from 'obsidian';
import { isPinterestHostname } from './pinterest';
import { t } from './i18n';

export interface OnlineImage {
  imageUrl: string;
  sourceUrl: string;
  title: string;
  width: number;
  height: number;
}

export function imageUrl(input: string): string {
  let url: URL;
  try { url = new URL(input.trim()); } catch { throw new Error(t('invalidImageUrl')); }
  if (url.protocol !== 'https:' || url.username || url.password || /[\u0000-\u001f]/.test(input)) {
    throw new Error(t('httpsOnly'));
  }
  return url.href.replace(/[<>]/g, c => encodeURIComponent(c));
}

/** Read the remote-image syntax generated by earlier plugin versions. */
export function markdownImageUrl(text: string): string | null {
  const match = /!\[(?:\\.|[^\]\\])*\]\(\s*(?:<([^>]+)>|(https:\/\/[^\s)]+))\s*\)/.exec(text);
  if (!match) return null;
  try { return imageUrl(match[1] ?? match[2]!); } catch { return null; }
}

function decodeEntities(text: string): string {
  return text.replace(/&(#x[\da-f]+|#\d+|amp|quot|apos|lt|gt);/gi, (match, entity: string) => {
    const names: Record<string, string> = { amp: '&', quot: '"', apos: "'", lt: '<', gt: '>' };
    if (!entity.startsWith('#')) return names[entity.toLowerCase()] ?? match;
    const code = entity[1]?.toLowerCase() === 'x' ? parseInt(entity.slice(2), 16) : parseInt(entity.slice(1), 10);
    return code > 0 && code <= 0x10ffff ? String.fromCodePoint(code) : match;
  });
}

/** Extract inert Open Graph metadata only; never evaluate Pinterest scripts. */
export function parsePinPreview(html: string, sourceUrl: string): OnlineImage {
  const metadata = new Map<string, string>();
  for (const tag of html.matchAll(/<meta\b(?:[^"'<>]|"[^"]*"|'[^']*')*>/gi)) {
    const attrs = new Map<string, string>();
    for (const attr of tag[0].matchAll(/([^\s=/>]+)\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'=<>`]+))/g)) {
      attrs.set(attr[1]!.toLowerCase(), decodeEntities(attr[2] ?? attr[3] ?? attr[4] ?? ''));
    }
    const key = (attrs.get('property') ?? attrs.get('name'))?.toLowerCase();
    if (key && !metadata.has(key)) metadata.set(key, attrs.get('content') ?? '');
  }
  const preview = metadata.get('og:image:secure_url') || metadata.get('og:image') || metadata.get('twitter:image');
  if (!preview) {
    throw new Error(t('pinNoPreview'));
  }
  const resolved = imageUrl(preview);
  // Pinterest previews belong on its image CDN, not an arbitrary URL from HTML.
  if (!/(^|\.)pinimg\.com$/i.test(new URL(resolved).hostname)) {
    throw new Error(t('pinInvalidPreview'));
  }
  const positive = (key: string, fallback: number): number => {
    const value = Number(metadata.get(key));
    return Number.isFinite(value) && value > 0 ? value : fallback;
  };
  return {
    imageUrl: resolved, sourceUrl,
    title: metadata.get('og:title') || 'Pinterest Pin',
    width: positive('og:image:width', 600), height: positive('og:image:height', 800),
  };
}

export async function resolveImageLink(input: string): Promise<OnlineImage> {
  const normalized = imageUrl(input);
  const url = new URL(normalized);
  if (url.hostname.toLowerCase() === 'pin.it' || url.hostname.toLowerCase().endsWith('.pin.it')) {
    throw new Error(t('noShortLinks'));
  }
  if (!isPinterestHostname(url.hostname)) {
    // Do not download remote image bytes: the board stores the URL and Obsidian
    // loads it when rendering, including on mobile.
    const name = url.pathname.split('/').filter(Boolean).pop() || t('onlineImage');
    return { imageUrl: normalized, sourceUrl: normalized, title: name, width: 600, height: 800 };
  }
  const match = /^\/pin\/(\d+)\/?$/.exec(url.pathname);
  if (!match) throw new Error(t('noBoardLink'));
  const sourceUrl = `https://www.pinterest.com/pin/${match[1]}/`;
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    const response = await Promise.race([
      requestUrl({ url: sourceUrl, throw: false, headers: { Accept: 'text/html' } }),
      new Promise<never>((_, reject) => {
        timer = setTimeout(() => reject(new Error(t('pinTimeout'))), 30_000);
      }),
    ]);
    if (response.status !== 200) {
      throw new Error(t('pinUnavailable', { status: response.status }));
    }
    return parsePinPreview(response.text, sourceUrl);
  } finally { if (timer !== undefined) clearTimeout(timer); }
}
